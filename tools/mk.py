def img(t):
    rows=[r for r in t.strip('\n').split('\n')];h=len(rows);w=max(len(r) for r in rows)
    im=Image.new('RGBA',(w,h),(0,0,0,0));px=im.load()
    for y,r in enumerate(rows):
        for x,c in enumerate(r.ljust(w,'.')):
            if PAL[c]:px[x,y]=PAL[c]+(255,)
    return im
def strip(frames):
    w=max(f.width for f in frames);h=max(f.height for f in frames)
    out=Image.new('RGBA',(w*len(frames),h),(0,0,0,0))
    for i,f in enumerate(frames):out.paste(f,(i*w+(w-f.width)//2,h-f.height))
    return out
def shift(t,pairs):
    for a,b in pairs:
        assert a in t,a[:30]; t=t.replace(a,b)
    return t
SPRITES={}
def add(name,frames):
    assert name not in PROTECTED,name+' is finished art'
    SPRITES[name]=strip(frames)

