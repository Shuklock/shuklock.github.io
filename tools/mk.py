def contact(names):
    ims=[Image.open(ART_DIR/(n+'.png')) for n in names];sc=5
    W=sum(i.width*sc for i in ims)+20*(len(ims)+1);H=max(i.height*sc for i in ims)+80
    sheet=Image.new('RGBA',(W,H),(14,11,28,255));x=20
    for im in ims:  # mirror-floor preview
        big=im.resize((im.width*sc,im.height*sc),Image.NEAREST);sheet.alpha_composite(big,(x,H-40-big.height))
        ref=big.transpose(Image.FLIP_TOP_BOTTOM);a=ref.split()[3].point(lambda v:int(v*.18));ref.putalpha(a);sheet.alpha_composite(ref,(x,H-40))
        x+=big.width+20
    PREVIEW_DIR.mkdir(exist_ok=True);out=PREVIEW_DIR/'contact.png';sheet.save(out);print('preview',out)

if __name__=='__main__':
    ap=argparse.ArgumentParser(description='Write placeholder sprites for art that has no Gemini version yet.')
    ap.add_argument('names',nargs='*',help='sprites to write (default: all placeholders)')
    ap.add_argument('--force',action='store_true',help='overwrite an existing PNG (never a Gemini one)')
    ap.add_argument('--preview',action='store_true',help='write tools/preview/contact.png')
    a=ap.parse_args()
    names=a.names or list(SPRITES)
    for n in names:
        if n in PROTECTED:ap.error(n+' is finished art; use tools/grid.py on a new render instead')
        if n not in SPRITES:ap.error('no grid for '+n+'; have: '+', '.join(SPRITES))
    for n in names:
        p=ART_DIR/(n+'.png')
        if p.exists() and not a.force:print('keep ',p.relative_to(ROOT),'(exists; --force to redraw)');continue
        SPRITES[n].save(p);print('wrote',p.relative_to(ROOT),SPRITES[n].size)
    if a.preview:contact([n for n in names if (ART_DIR/(n+'.png')).exists()])
