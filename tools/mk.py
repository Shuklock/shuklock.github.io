#
# The Gemini sprites (warlock, pet_imp, pet_vw, pet_succ) are the real art and this script
# never writes them. It only fills gaps: by default it writes a placeholder only when
# drain-soul/art/<name>.png does not exist, so dropping in a Gemini sprite retires the grid.
#
#   python3 tools/mk.py                 # write any missing placeholders
#   python3 tools/mk.py pet_felh --force   # redraw one placeholder over itself
#   python3 tools/mk.py --preview       # also write tools/preview/contact.png (not committed)
#
# Grids are 2-frame strips facing right. Their ART entry in index.html is {frames:2,fps:2,scale:N}
# with N chosen so they stand at the right height next to the Gemini sprites.
